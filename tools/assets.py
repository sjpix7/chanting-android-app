def n(v): return ("%.2f" % v).rstrip("0").rstrip(".")

# ---------------------------------------------------------------- geometry helpers
def circle(cx, cy, r):
    return f"M{n(cx-r)},{n(cy)}a{n(r)},{n(r)} 0 1,0 {n(2*r)},0a{n(r)},{n(r)} 0 1,0 {n(-2*r)},0Z"

def polar(cx, cy, r, deg):
    a = math.radians(deg); return cx + r*math.cos(a), cy + r*math.sin(a)

def diamond(cx, cy, r):
    return f"M{n(cx)},{n(cy-r)}L{n(cx+r)},{n(cy)}L{n(cx)},{n(cy+r)}L{n(cx-r)},{n(cy)}Z"

def bead_ring(cx, cy, R, count, r, meru_r):
    slots = count + 1
    beads = "".join(circle(*polar(cx, cy, R, -90 + (i+1)*360/slots), r) for i in range(count))
    mx, my = polar(cx, cy, R, -90)
    meru = circle(mx, my, meru_r)
    tassel = (f"M{n(mx)},{n(my-meru_r)}L{n(mx-meru_r*0.8)},{n(my-meru_r*2.7)}"
              f"L{n(mx)},{n(my-meru_r*2.2)}L{n(mx+meru_r*0.8)},{n(my-meru_r*2.7)}Z")
    return beads, meru + tassel

def glyph_path(font_path, codepoint, cx, cy, height):
    f = TTFont(font_path); gs = f.getGlyphSet(); name = f.getBestCmap()[codepoint]
    bp = BoundsPen(gs); gs[name].draw(bp); x0, y0, x1, y1 = bp.bounds
    s = height / (y1 - y0)
    pen = SVGPathPen(gs, ntos=n)
    gs[name].draw(TransformPen(pen, (s, 0, 0, -s, cx - (x0+x1)/2*s, cy + (y0+y1)/2*s)))
    return pen.getCommands(), (x1-x0)*s

def text_path(font_path, text, size, wght=None, tracking=0.0):
    """Shape with HarfBuzz (handles Devanagari conjuncts) and return (path at origin baseline, width)."""
    blob = hb.Blob.from_file_path(font_path); face = hb.Face(blob); font = hb.Font(face)
    loc = None
    if wght is not None:
        font.set_variations({"wght": wght}); loc = {"wght": wght}
    buf = hb.Buffer(); buf.add_str(text); buf.guess_segment_properties(); hb.shape(font, buf, {})
    tt = TTFont(font_path); gs = tt.getGlyphSet(location=loc) if loc else tt.getGlyphSet(); order = tt.getGlyphOrder()
    s = size / face.upem; x = 0.0; parts = []
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        pen = SVGPathPen(gs, ntos=n)
        gs[order[info.codepoint]].draw(TransformPen(pen, (s, 0, 0, -s, x + pos.x_offset*s, -pos.y_offset*s)))
        parts.append(pen.getCommands()); x += pos.x_advance*s + tracking
    return "".join(parts), x - tracking

