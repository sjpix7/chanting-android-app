# ---------------------------------------------------------------- temple bell (synthesised, mono 22.05 kHz)
rate, dur, f0 = 22050, 3.2, 587.0
partials = [(0.5, 0.35, 2.6), (1.0, 1.0, 1.9), (1.183, 0.55, 1.4), (1.506, 0.42, 1.2),
            (2.0, 0.6, 1.0), (2.514, 0.25, 0.7), (2.662, 0.22, 0.6), (3.011, 0.18, 0.5), (4.166, 0.10, 0.3)]
random.seed(7)
samples = []
for i in range(int(rate*dur)):
    t = i / rate
    attack = min(1.0, t / 0.003)
    v = sum(a * math.exp(-t / d) * math.sin(2*math.pi*f0*ratio*t + ratio) for ratio, a, d in partials)
    v *= attack * (1 + 0.04*math.sin(2*math.pi*4.5*t))  # slow shimmer
    if t < 0.012: v += (random.random()*2-1) * 0.25 * (1 - t/0.012)  # mallet strike
    samples.append(v)
peak = max(abs(s) for s in samples)
with wave.open(os.path.join(RES, "raw/temple_bell.wav"), "wb") as w:
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(rate)
    w.writeframes(b"".join(struct.pack("<h", int(s/peak*0.85*32767)) for s in samples))
